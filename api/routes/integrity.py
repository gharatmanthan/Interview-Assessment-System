import asyncio
import json
from fastapi import APIRouter, Depends, Header, HTTPException, WebSocket, WebSocketDisconnect
from api.deps import get_current_recruiter, InterviewTokenInvalid, _interview_identity
from api.schemas import IntegrityFlagBatch, IntegrityFlagResponse
from app.core import db
from app.core.models import IntegrityFlag
from app.candidate.integrity import run_checks, ExternalDeviceMonitor
from app.core.tokens import verify_token

router = APIRouter()


def _owned_session_ids(username: str) -> set:
    return {s["session_id"] for s in db.get_owned_sessions(username)}


@router.get("/integrity/flags", response_model=list[IntegrityFlagResponse])
def list_integrity_flags(username: str = Depends(get_current_recruiter)):
    """Ownership-scoped: only flags for the recruiter's own interviews."""
    owned = _owned_session_ids(username)
    return [f for f in db.get_all_integrity_flags() if f.get("session_id") in owned]


@router.post("/integrity/flags")
def receive_integrity_flags(
    batch: IntegrityFlagBatch,
    x_interview_token: str = Header(default=""),
):
    """Intake for flags generated by a LOCAL scan on the candidate's machine.

    Port/process scanning only means anything on the machine being monitored,
    so in remote mode the candidate's Electron app runs the scan itself
    (native, inside Electron) and posts results to this shared endpoint.
    The central server never runs these scans itself in remote mode — it has
    no visibility into the candidate's network or processes.

    Authenticated by the candidate's X-Interview-Token; every reported flag
    must belong to a session this candidate owns.
    """
    candidate_id, job_id = _interview_identity(x_interview_token)
    candidate = db.get_candidate(candidate_id)
    if not candidate or candidate.get("job_id") != job_id:
        raise InterviewTokenInvalid()
    owned_session = candidate.get("session_id")
    if owned_session and any(item.session_id != owned_session for item in batch.flags):
        raise HTTPException(
            status_code=403,
            detail="Flags reference a session that does not belong to this candidate.",
        )
    saved = 0
    for item in batch.flags:
        if owned_session and item.session_id != owned_session:
            continue
        kwargs = dict(
            session_id=item.session_id,
            flag_type=item.flag_type,
            detail=item.detail,
            severity=item.severity,
        )
        if item.timestamp:
            kwargs["timestamp"] = item.timestamp
        db.save_integrity_flag(IntegrityFlag(**kwargs))
        saved += 1
    return {"saved": saved}


@router.get("/bias/flags")
def list_bias_flags(username: str = Depends(get_current_recruiter)):
    owned = _owned_session_ids(username)
    return [f for f in db.get_all_fairness_flags() if f.get("session_id") in owned]


@router.websocket("/ws/integrity/{session_id}")
async def integrity_ws(websocket: WebSocket, session_id: str):
    """Recruiter-only live integrity feed. The recruiter's Bearer token must be
    passed as ?token=... because browsers can't set headers on WebSockets."""
    token = websocket.query_params.get("token", "")
    username = verify_token(token)
    if not username:
        await websocket.accept()
        await websocket.close(code=4401, reason="Authentication required")
        return
    await websocket.accept()
    monitor = ExternalDeviceMonitor(session_id)
    monitor.start()

    try:
        while True:
            flags = run_checks(session_id)
            poll_flags = monitor.poll()
            all_flags = flags + poll_flags

            for flag in all_flags:
                db.save_integrity_flag(flag)

            await websocket.send_json({
                "flags": [
                    {
                        "flag_type": f.flag_type,
                        "detail": f.detail,
                        "severity": f.severity,
                    }
                    for f in all_flags
                ],
                "total_flags": len(all_flags),
            })
            await asyncio.sleep(5)
    except WebSocketDisconnect:
        pass
